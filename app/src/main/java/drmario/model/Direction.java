package drmario.model;

/**
 * Represents the orientation of a capsule.
 * <p>
 * A capsule consists of two halves:
 * <ul>
 *     <li>HORIZONTAL: [A][B] — side by side</li>
 *     <li>VERTICAL: [A] on top, [B] below</li>
 * </ul>
 *
 * @author DANIL-lab1
 * @version 1.0
 */
public enum Direction {
    HORIZONTAL,
    VERTICAL
}